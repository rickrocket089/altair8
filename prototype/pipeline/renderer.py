def _render_visual(vs, section_id: str) -> str:
    if not vs.spec or not vs.validation_passed:
        return (
            f'<div class="visual-block visual-failed">'
            f'⚠ Visual "{html.escape(vs.caption)}" could not be rendered '
            f"(generation or validation failed). Flagged, not silently dropped."
            f"</div>"
        )
    if vs.content_grounded is False:
        issues = "; ".join(vs.grounding_issues) or "content did not match the section topic"
        return (
            f'<div class="visual-block visual-failed">'
            f'⚠ Visual "{html.escape(vs.caption)}" was structurally valid but failed the '
            f"content-grounding check ({html.escape(issues)}). Withheld rather than shown, "
            f"since a technically-correct-but-off-topic chart is worse than none."
            f"</div>"
        )
    chart_div_id = f"chart-{section_id}-{vs.slot_id}"
    spec_json = json.dumps(_make_responsive(vs.spec))
    illustrative_badge = '<div class="illustrative-badge">Illustrative data — not retrieved from live sources</div>' if vs.illustrative else ""
    return f"""<div class="visual-block">
  {illustrative_badge}
  <div id="{chart_div_id}"></div>
  <div class="visual-caption">{html.escape(vs.caption)}</div>
  <script>vegaEmbed('#{chart_div_id}', {spec_json}, {{actions: false}});</script>
</div>"""


def render(doc: PipelineDocument) -> str:
    nav_links = "\n".join(f'<a href="#{s.id}">{html.escape(s.title)}</a>' for s in doc.sections)

    sections_html = []
    for section in doc.sections:
        prose_html = "\n".join(f"<p>{html.escape(p)}</p>" for p in section.prose_blocks)
        visuals_html = "\n".join(_render_visual(vs, section.id) for vs in section.visual_slots)
        sections_html.append(f"""<section class="content-section" id="{section.id}">
  <h2>{html.escape(section.title)}</h2>
  <div class="prose">{prose_html}</div>
  {visuals_html}
</section>""")

    notes_html = ""
    if doc.global_notes:
        items = "\n".join(f"<li>{html.escape(n)}</li>" for n in doc.global_notes)
        notes_html = f'<div class="global-notes"><strong>Pipeline notes:</strong><ul>{items}</ul></div>'

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{html.escape(doc.title)}</title>
{VEGA_CDN}
{STYLE}
</head>
<body>
<div class="layout">
  <nav>{nav_links}</nav>
  <main>
    <header class="doc-header">
      <h1>{html.escape(doc.title)}</h1>
      <p class="meta">Audience: {html.escape(doc.audience)} &middot; Goal: {html.escape(doc.goal)}<br>
      Generated {html.escape(doc.generated_at)} by Altair8's Sprint 8 prototype pipeline.</p>
    </header>
    {''.join(sections_html)}
    {notes_html}
  </main>
</div>
</body>
</html>
"""
