"""Stage 4 -- HTML Renderer.

A renderer, not a writer (Ingrid's review, must-fix #3): this stage
consumes a complete PipelineDocument and materializes it as HTML. It does
not generate new prose or new specs -- any judgment call it can't resolve
mechanically (e.g. a visual that failed validation) is logged to
global_notes and shown as a visible placeholder, never silently dropped or
silently fixed by re-invoking an LLM.

v1 targets a single self-contained HTML file, Vega-Lite rendered
client-side via CDN (vega-embed) -- no build step. This is design principle
#4's first concrete step, explicitly short of its full ambition (no zoom-
as-navigation, no motion, no true multi-dimensional/spatial views yet --
see the Sprint 8 prototype proposal for why this step was chosen anyway).
"""
