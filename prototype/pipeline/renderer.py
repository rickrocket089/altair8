# Vega-Lite specs generated by the Stage 2 LLM tend to hardcode a fixed
# pixel width (e.g. 820) chosen without any knowledge of the actual page
# layout -- on Sprint 8's first real runs this made charts overflow the
# content column, which is narrower than 820px once the nav sidebar and
# padding are accounted for. The renderer's job is to materialize content
# correctly regardless of what Stage 2 assumed about its own container, so
# the fix belongs here, not in Stage 2.
#
# First attempt used "width": "container" + autosize, which is the "correct"
# Vega-Lite-native way to do this -- but it depends on the embedding div
# having a resolved CSS width at the moment vega-embed reads it, and has
# known inconsistent support across composite view types (layer/facet/
# concat). It silently failed in a real browser (no charts rendered at all,
# not just wrong-sized ones) in a way this environment can't catch without
# an actual browser -- caught only because the founder opened the file and
# reported it, not by any automated check here. Replaced with something
# that doesn't depend on vega-embed's container-sizing behavior at all:
# clamp every explicit numeric width to a safe static maximum that's known
# to fit the content column. Less elegant, much less likely to silently
# break.
_COMPOSITE_KEYS = ("layer", "concat", "hconcat", "vconcat", "facet", "repeat")
_MAX_CHART_WIDTH = 640  # safely inside the ~750-770px content column at 1100px page width


def _clamp_widths(node) -> None:
    """Recursively cap any numeric 'width' key to _MAX_CHART_WIDTH, in
    place. Only touches numeric widths -- never introduces "container" or
    any autosize behavior, to avoid the exact failure mode above."""
    if isinstance(node, dict):
        w = node.get("width")
        if isinstance(w, (int, float)) and w > _MAX_CHART_WIDTH:
            node["width"] = _MAX_CHART_WIDTH
        for v in node.values():
            _clamp_widths(v)
    elif isinstance(node, list):
        for item in node:
            _clamp_widths(item)


def _make_responsive(spec: dict) -> dict:
    spec = copy.deepcopy(spec)
    if isinstance(spec.get("width"), (int, float)):
        spec["width"] = min(spec["width"], _MAX_CHART_WIDTH)
    else:
        spec.setdefault("width", _MAX_CHART_WIDTH)
    _clamp_widths(spec)
    return spec

